create table if not exists public.report_secrets (
  report_id bigint primary key references public.reports (id) on delete cascade,
  expected_answer text not null default ''
);

-- Migrate answers from the earlier draft schema before removing the exposed column.
do $$
begin
  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'reports'
      and column_name = 'expected_answer'
  ) then
    execute $copy$
      insert into public.report_secrets (report_id, expected_answer)
      select id, coalesce(expected_answer, '') from public.reports
      on conflict (report_id) do update
        set expected_answer = excluded.expected_answer
    $copy$;
    alter table public.reports drop column expected_answer;
  end if;
end;
$$;

