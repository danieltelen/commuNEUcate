-- Used by row-level policies without recursively querying profiles as the caller.
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and role = 'admin'
  );
$$;

create or replace function public.is_neu_user()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
      select 1 from auth.users u
      where u.id = (select auth.uid())
        and u.email_confirmed_at is not null
    )
    and (
      lower(coalesce(auth.jwt() ->> 'email', '')) ~ '^[^@]+@neu\.edu\.ph$'
      or (select public.is_admin())
    );
$$;

create or replace function public.has_app_access()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.is_neu_user() and exists (
    select 1 from public.profiles
    where id = (select auth.uid())
      and (account_status = 'approved' or role = 'admin')
  );
$$;

-- Check for a pending claim without invoking claims RLS from a reports policy.
create or replace function public.has_pending_claim_for_report(target_report_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.claims c
    where c.report_id = target_report_id
      and c.claimer_id = (select auth.uid())
      and c.status = 'pending'
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;
revoke all on function public.is_neu_user() from public;
grant execute on function public.is_neu_user() to authenticated;
