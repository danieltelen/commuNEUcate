select
  id,
  email,
  coalesce(raw_user_meta_data ->> 'full_name', raw_user_meta_data ->> 'name'),
  'user'
from auth.users
on conflict (id) do update
  set email = excluded.email,
      full_name = coalesce(public.profiles.full_name, excluded.full_name);

-- Existing Google signups no longer need to wait for manual account approval.
-- Keep denied accounts denied and leave email/password signups pending.
update public.profiles p
set account_status = 'approved'
from auth.users u
where p.id = u.id
  and p.role = 'user'
  and p.account_status = 'pending'
  and u.raw_app_meta_data ->> 'provider' = 'google';

-- Prevent a normal signed-in user from promoting themselves or changing report ownership/status.
create or replace function public.guard_user_mutations()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  if tg_table_name = 'profiles' then
    if auth.uid() is not null and not public.is_admin() then
      if new.id is distinct from old.id or new.email is distinct from old.email then
        raise exception 'Profile identity cannot be changed';
      end if;
      if new.role is distinct from old.role then
        raise exception 'Only an admin can change a profile role';
      end if;
      if new.account_status is distinct from old.account_status then
        raise exception 'Only an admin can change account approval';
      end if;
    end if;
  elsif tg_table_name = 'reports' then
    if tg_op = 'INSERT' and auth.uid() is not null and not public.is_admin() then
      if new.reporter_id is distinct from (select auth.uid())
         or new.status is distinct from 'pending_review'
         or new.revalidation_count is distinct from 0
         or new.review_note is not null
         or new.reviewed_at is not null
         or new.reviewed_by is not null then
        raise exception 'Users may only create a new pending report';
      end if;
    elsif auth.uid() is not null and not public.is_admin() then
      if new.reporter_id is distinct from old.reporter_id then
        raise exception 'Report owner cannot be changed';
      end if;
      if old.reporter_id <> (select auth.uid()) and (
        new.item_name is distinct from old.item_name
        or new.category is distinct from old.category
        or new.location_found is distinct from old.location_found
        or new.date_found is distinct from old.date_found
        or new.description is distinct from old.description
        or new.tags is distinct from old.tags
        or new.security_question is distinct from old.security_question
        or new.image_url is distinct from old.image_url
        or new.review_note is distinct from old.review_note
        or new.reviewed_at is distinct from old.reviewed_at
        or new.reviewed_by is distinct from old.reviewed_by
        or new.revalidation_count is distinct from old.revalidation_count
      ) then
        raise exception 'A claimant cannot edit another user report';
      end if;
      if new.status is distinct from old.status
         and not (
           old.status = 'unclaimed'
           and new.status = 'pending_review'
           and exists (
             select 1 from public.claims c
             where c.report_id = old.id and c.claimer_id = (select auth.uid()) and c.status = 'pending'
           )
         )
         and not (
           old.status = 'rejected'
           and new.status = 'pending_review'
           and new.revalidation_count = old.revalidation_count + 1
           and new.review_note is null
           and new.reviewed_at is null
           and new.reviewed_by is null
         ) then
        raise exception 'Only an admin can approve or reject a report';
      end if;
      if new.revalidation_count is distinct from old.revalidation_count
         and not (old.status = 'rejected' and new.status = 'pending_review'
           and new.revalidation_count = old.revalidation_count + 1) then
        raise exception 'Only a rejected report can be revalidated';
      end if;
      if (new.review_note is distinct from old.review_note
          or new.reviewed_at is distinct from old.reviewed_at
          or new.reviewed_by is distinct from old.reviewed_by)
         and not (old.status = 'rejected' and new.status = 'pending_review'
           and new.review_note is null and new.reviewed_at is null and new.reviewed_by is null) then
        raise exception 'Only an admin can change review details';
      end if;
    end if;
  elsif tg_table_name = 'claims' then
    if auth.uid() is not null and not public.is_admin() then
      if new.claimer_id is distinct from old.claimer_id
         or new.report_id is distinct from old.report_id
         or new.status is distinct from old.status then
        raise exception 'Only an admin can change claim ownership or status';
      end if;
    end if;
  end if;
  return new;
end;
$$;

